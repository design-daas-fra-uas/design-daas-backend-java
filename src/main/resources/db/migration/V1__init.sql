-- ============================================================
-- V1__init.sql  –  Design DaaS Backend schema (PostgreSQL)
--
-- The whole schema in one script. It replaces the five MariaDB migrations
-- (V1-V5, see git history) from when the service ran on MariaDB; the data
-- was copied over on 2026-11-17.
--
-- Ids are identity columns (GenerationType.IDENTITY in the entities); every
-- java.time.Instant is a TIMESTAMPTZ (stored as UTC).
-- ============================================================

-- ---- Application tables ----

-- Admins and users in one table; role is the JPA discriminator ("admin"/"user")
CREATE TABLE users
(
    id                        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role                      VARCHAR(16)  NOT NULL,
    name                      VARCHAR(255) NOT NULL,
    email                     VARCHAR(255) NOT NULL UNIQUE,
    password                  VARCHAR(255) NOT NULL,
    enabled                   BOOLEAN      NOT NULL DEFAULT FALSE,
    registration_code         VARCHAR(8),
    registration_code_timeout TIMESTAMPTZ(6),
    registration_used_moment  TIMESTAMPTZ(6),
    failed_login_attempts     INT          NOT NULL DEFAULT 0,
    locked_until              TIMESTAMPTZ(6)
);

CREATE TABLE user_groups
(
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL UNIQUE,
    description VARCHAR(255)
);

CREATE TABLE users_to_user_groups
(
    user_id       INT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    user_group_id INT NOT NULL REFERENCES user_groups (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, user_group_id)
);

-- Desktop groups are identified by their description only
CREATE TABLE desktop_groups
(
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description VARCHAR(255) NOT NULL,
    CONSTRAINT uq_desktop_groups_description UNIQUE (description)
);

-- Desktops are identified by their description only
CREATE TABLE desktops
(
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description VARCHAR(255)
);

CREATE TABLE desktops_to_desktop_groups
(
    desktop_id       INT NOT NULL REFERENCES desktops (id) ON DELETE CASCADE,
    desktop_group_id INT NOT NULL REFERENCES desktop_groups (id) ON DELETE CASCADE,
    PRIMARY KEY (desktop_id, desktop_group_id)
);

CREATE TABLE user_group_to_desktop_group
(
    user_group_id    INT NOT NULL REFERENCES user_groups (id) ON DELETE CASCADE,
    desktop_group_id INT NOT NULL REFERENCES desktop_groups (id) ON DELETE CASCADE,
    PRIMARY KEY (user_group_id, desktop_group_id)
);

CREATE TABLE endpoints
(
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    function_name VARCHAR(255) NOT NULL UNIQUE,
    description   VARCHAR(255)
);

CREATE TABLE endpoint_groups
(
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL UNIQUE,
    description VARCHAR(255)
);

CREATE TABLE endpoint_group_members
(
    endpoint_group_id INT NOT NULL REFERENCES endpoint_groups (id) ON DELETE CASCADE,
    endpoint_id       INT NOT NULL REFERENCES endpoints (id) ON DELETE CASCADE,
    PRIMARY KEY (endpoint_group_id, endpoint_id)
);

-- ---- Permission rules: at most one per subject, target and kind ----

CREATE TABLE endpoint_user_access
(
    id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      INT     NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    endpoint_id  INT     NOT NULL REFERENCES endpoints (id) ON DELETE CASCADE,
    allow_access BOOLEAN NOT NULL,
    CONSTRAINT uq_endpoint_user_access UNIQUE (user_id, endpoint_id)
);

CREATE TABLE endpoint_user_group_access
(
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_group_id INT     NOT NULL REFERENCES user_groups (id) ON DELETE CASCADE,
    endpoint_id   INT     NOT NULL REFERENCES endpoints (id) ON DELETE CASCADE,
    allow_access  BOOLEAN NOT NULL,
    CONSTRAINT uq_endpoint_user_group_access UNIQUE (user_group_id, endpoint_id)
);

CREATE TABLE endpoint_group_user_access
(
    id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           INT     NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    endpoint_group_id INT     NOT NULL REFERENCES endpoint_groups (id) ON DELETE CASCADE,
    allow_access      BOOLEAN NOT NULL,
    CONSTRAINT uq_endpoint_group_user_access UNIQUE (user_id, endpoint_group_id)
);

CREATE TABLE endpoint_group_user_group_access
(
    id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_group_id     INT     NOT NULL REFERENCES user_groups (id) ON DELETE CASCADE,
    endpoint_group_id INT     NOT NULL REFERENCES endpoint_groups (id) ON DELETE CASCADE,
    allow_access      BOOLEAN NOT NULL,
    CONSTRAINT uq_endpoint_group_user_group_access UNIQUE (user_group_id, endpoint_group_id)
);

-- ---- Auth tables (custom JWT issuance, not Spring Authorization Server) ----

CREATE TABLE refresh_tokens
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_value VARCHAR(255)   NOT NULL UNIQUE,
    user_id     INT            NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    scope       VARCHAR(20)    NOT NULL,
    created_at  TIMESTAMPTZ(6) NOT NULL,
    expires_at  TIMESTAMPTZ(6) NOT NULL,
    revoked     BOOLEAN        NOT NULL DEFAULT FALSE,
    revoked_at  TIMESTAMPTZ(6)
);
CREATE INDEX idx_refresh_tokens_user_id ON refresh_tokens (user_id);

CREATE TABLE access_tokens
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jti        VARCHAR(200)   NOT NULL UNIQUE,
    user_id    INT            NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    scope      VARCHAR(20)    NOT NULL,
    issued_at  TIMESTAMPTZ(6) NOT NULL,
    expires_at TIMESTAMPTZ(6) NOT NULL,
    revoked    BOOLEAN        NOT NULL DEFAULT FALSE,
    revoked_at TIMESTAMPTZ(6)
);
CREATE INDEX idx_access_tokens_user_id ON access_tokens (user_id);
CREATE INDEX idx_access_tokens_expires_at ON access_tokens (expires_at);
